export function getInitialMomentByHour(): UserContext['moment'] {
  const hour = new Date().getHours();
  if (hour >= 6 && hour < 11) return 'desayuno';
  if (hour >= 11 && hour < 16) return 'almuerzo';
  if (hour >= 16 && hour < 20) return 'merienda';
  return 'cena';
}

